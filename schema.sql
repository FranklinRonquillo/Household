-- 1. TABLA: expenses (Registro de Gastos del Hogar)
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  descripcion text not null,
  monto numeric not null default 0,
  categoria text not null,
  pagado_por text not null,
  tipo_gasto text not null,
  fecha text not null
);

-- 2. TABLA: debts (Deudas y Pagos Pendientes)
create table if not exists public.debts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  concept text not null,
  amount numeric not null default 0,
  due_date text,
  type text,
  status text default 'pendiente'
);

-- 3. TABLA: savings_goals (Metas de Ahorro)
create table if not exists public.savings_goals (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  title text not null,
  current numeric not null default 0,
  target numeric not null default 0,
  icon text
);

-- 4. TABLA: market_items (Lista del Mercado Inteligente)
create table if not exists public.market_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  name text not null,
  price numeric not null default 0,
  category text,
  checked boolean not null default false
);

-- 5. TABLA: memories (Álbum de Recuerdos del Hogar)
create table if not exists public.memories (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  title text not null,
  date text,
  description text,
  image_url text
);

-- 6. TABLA: household_settings (Configuración, Sueldos, Frase, Presupuestos y Recordatorios)
create table if not exists public.household_settings (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz default now()
);

-- ==============================================================================
-- REPLICA IDENTITY (Garantiza que Realtime transmita registros completos en UPDATE y DELETE)
-- ==============================================================================
alter table public.expenses replica identity full;
alter table public.debts replica identity full;
alter table public.savings_goals replica identity full;
alter table public.market_items replica identity full;
alter table public.memories replica identity full;
alter table public.household_settings replica identity full;

-- ==============================================================================
-- POLÍTICAS DE ACCESO (Row Level Security - RLS)
-- Permite lectura, inserción, actualización y borrado seguro para la app del hogar
-- ==============================================================================

alter table public.expenses enable row level security;
alter table public.debts enable row level security;
alter table public.savings_goals enable row level security;
alter table public.market_items enable row level security;
alter table public.memories enable row level security;
alter table public.household_settings enable row level security;

do $$
begin
  -- expenses
  if not exists (select 1 from pg_policies where policyname = 'household_public_expenses') then
    create policy "household_public_expenses" on public.expenses for all using (true) with check (true);
  end if;
  -- debts
  if not exists (select 1 from pg_policies where policyname = 'household_public_debts') then
    create policy "household_public_debts" on public.debts for all using (true) with check (true);
  end if;
  -- savings_goals
  if not exists (select 1 from pg_policies where policyname = 'household_public_savings_goals') then
    create policy "household_public_savings_goals" on public.savings_goals for all using (true) with check (true);
  end if;
  -- market_items
  if not exists (select 1 from pg_policies where policyname = 'household_public_market_items') then
    create policy "household_public_market_items" on public.market_items for all using (true) with check (true);
  end if;
  -- memories
  if not exists (select 1 from pg_policies where policyname = 'household_public_memories') then
    create policy "household_public_memories" on public.memories for all using (true) with check (true);
  end if;
  -- household_settings
  if not exists (select 1 from pg_policies where policyname = 'household_public_settings') then
    create policy "household_public_settings" on public.household_settings for all using (true) with check (true);
  end if;
end $$;

